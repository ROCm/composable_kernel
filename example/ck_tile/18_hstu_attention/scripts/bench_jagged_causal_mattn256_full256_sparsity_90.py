def run(exe_prefix, dtype, b, seqlens, max_seqlen):
    """Build and execute a single benchmark case, echoing the command."""
    cmd = (
        exe_prefix
        + ["-v=0", f"-prec={dtype}", f"-b={b}", "-jagged=1", "-nhead=4",
           "-hdim_qk=128", "-hdim_v=128", f"-seqlens={seqlens}", "-causal=1",
           "-local_len=256", "-context_len=0", "-minfull_len=256",
           "-targets=200", f"-max_seqlen={max_seqlen}", "-perf=1",
           "-alpha=0.0078125"]
    )
    print("+ " + " ".join(cmd), flush=True)
    result = subprocess.run(cmd)
    print("")
    return result.returncode


def main():
    parser = argparse.ArgumentParser(
        description="Benchmark HSTU attention forward (jagged causal mattn256 full256 sparsity 0.9).")
    parser.add_argument("use_softmax", nargs="?", type=int, default=0,
                        help="use softmax (default: 0)")
    args = parser.parse_args()

    binary = f"{BUILD}/bin/tile_example_hstu_attention"
    if args.use_softmax == 1:
        exe_prefix = [binary, "-softmax=1"]
    else:
        exe_prefix = [binary]

    dtype = "bf16"

    cases = [
        (8, seqlens8, 16184),
        (16, seqlens16, 16184),
        (32, seqlens32, 16184),
        (64, seqlens64, 16184),
        (128, seqlens128, 16184),
        (256, seqlens256_0, 3896),
        (256, seqlens256_1, 7992),
        (256, seqlens256_2, 16184),
    ]

    rc = 0
    for b, seqlens, max_seqlen in cases:
        ret = run(exe_prefix, dtype, b, seqlens, max_seqlen)
        if ret != 0:
            rc = ret

    return rc


if __name__ == "__main__":
    sys.exit(main())
