# Custom tune-config driven factory
#
# When the env var CK_TILE_FMHA_FWD_CUSTOM_TUNE_CONFIG_FILE points to a JSON
# file, `get_factory` will build a dynamic factory that:
#   * inherits everything (arch, supported_dtypes, get_pipelines) from an
#     arch base factory (selected via the JSON "target" field);
#   * replaces `get_hdim_tile_size_dict` with the JSON-declared tile table,
#     so that codegen ONLY emits kernels for the (hdim, hdim_v) keys the
#     tuner asked for;
#   * optionally drops `check_hdim_tile` rule (needed for arbitrary padded
#     hdim combos such as (80, 96));
#   * appends a "filters" compatibility rule that narrows pipelines to a
#     concrete combo (mode / mask / bias / lse / dropout / logits / qscale /
#     vlayout / skip / sink / trload / spad / skpad / dpad / dvpad).
#
# JSON schema (v1):
# {
#   "schema_version": 1,
#   "target": "gfx942",
#   "dtypes": ["bf16"],
#   "tiles": {
#     "bf16": {
#       "80,96": [
#         {"F_bm0":64,"F_bn0":64,"F_bk0":32,"F_bn1":96,"F_bk1":32,
#          "F_bk0max":128,"F_rm0":4,"F_rn0":1,"F_rk0":1,
#          "F_rm1":4,"F_rn1":1,"F_rk1":1,
#          "F_wm0":16,"F_wn0":16,"F_wk0":32,
#          "F_wm1":16,"F_wn1":16,"F_wk1":32,"F_occupancy":-1}
#       ]
#     }
#   },
#   "filters": {
#     "mode": ["group"], "mask": ["mask_bottom_right"],
#     "bias": ["no"], "lse": ["f"], "dropout": ["f"],
#     "logits": ["f"], "qscale": ["no"], "vlayout": ["row"]
#   },
#   "relax_rules": {"disable_check_hdim_tile": false}
# }
# ---------------------------------------------------------------------------


def _load_custom_tune_config() -> Optional[dict]:
    path = os.environ.get("CK_TILE_FMHA_FWD_CUSTOM_TUNE_CONFIG_FILE", "").strip()
    if not path:
        return None
    with open(path, "r") as f:
        cfg = json.load(f)
    return cfg


def _tune_config_pick_base(target: str):
    # Same dispatch as the tail of `get_factory` below, but consulted only
    # to select the base class for a dynamic factory.
    if target.startswith("gfx950"):
        return KernelComponentFactoryGfx950
    if target.startswith("gfx9"):
        return KernelComponentFactoryGfx9
    if target.startswith("gfx115"):
        return KernelComponentFactoryGfx115
    if target.startswith("gfx11"):
        return KernelComponentFactoryGfx11
    if target.startswith("gfx125"):
        return KernelComponentFactoryGfx125
    if target.startswith("gfx12"):
        return KernelComponentFactoryGfx12
    raise Exception(f"Unsupported device target {target} in tune config")


def _parse_tune_config_tiles(
    tiles_by_dtype_json: dict,
) -> Dict[str, Dict[Tuple[int, int], List[FmhaFwdTileSize]]]:
    result: Dict[str, Dict[Tuple[int, int], List[FmhaFwdTileSize]]] = {}
    for dtype, hkey_map in tiles_by_dtype_json.items():
        by_hkey: Dict[Tuple[int, int], List[FmhaFwdTileSize]] = {}
        for hkey, tile_dicts in hkey_map.items():
            parts = [p.strip() for p in str(hkey).split(",")]
            if len(parts) != 2:
                raise ValueError(
                    f"[CustomTuneFactory] tile key '{hkey}' must be 'HDIM,HDIMV'"
                )
            hdim, hdim_v = int(parts[0]), int(parts[1])
            tiles: List[FmhaFwdTileSize] = []
            for td in tile_dicts:
                # Optional runtime dispatch constraint (custom-tune JSON only).
                # Kept purely as a string so it can carry arbitrary C++
                # boolean expressions referring to fmha_fwd_args `a` and
                # fmha_fwd_traits `t` (e.g. "a.max_seqlen_q < 704" or
                # "(a.max_seqlen_q >= 704 && a.max_seqlen_q < 1344) || ...").
                # Missing/empty -> keep default CppConstraint (== "true").
                _cc = td.get("cpp_constraint")
                _cc_str = str(_cc).strip() if _cc is not None else ""
                _constraint = (
                    CppConstraint(bool_expr=_cc_str) if _cc_str else CppConstraint()
                )
                tiles.append(
                    FmhaFwdTileSize(
                        F_bm0=int(td["F_bm0"]),
                        F_bn0=int(td["F_bn0"]),
                        F_bk0=int(td["F_bk0"]),
                        F_bn1=int(td["F_bn1"]),
                        F_bk1=int(td["F_bk1"]),
                        F_bk0max=int(td["F_bk0max"]),
                        F_rm0=int(td["F_rm0"]),
                        F_rn0=int(td["F_rn0"]),
                        F_rk0=int(td["F_rk0"]),
                        F_rm1=int(td["F_rm1"]),
                        F_rn1=int(td["F_rn1"]),
                        F_rk1=int(td["F_rk1"]),
                        F_wm0=int(td["F_wm0"]),
                        F_wn0=int(td["F_wn0"]),
                        F_wk0=int(td["F_wk0"]),
                        F_wm1=int(td["F_wm1"]),
                        F_wn1=int(td["F_wn1"]),
                        F_wk1=int(td["F_wk1"]),
                        F_occupancy=int(td["F_occupancy"]),
                        F_constraint=_constraint,
                    )
                )
            by_hkey[(hdim, hdim_v)] = tiles
        result[dtype] = by_hkey
    return result


def _make_tune_filter_rule(filters: dict, normalize_batch_skip: bool = False):
    if not filters:
        return None

    allowed_mode = set(filters.get("mode", [])) or None
    allowed_mask = set(filters.get("mask", [])) or None
    allowed_bias = set(filters.get("bias", [])) or None
    allowed_lse = set(filters.get("lse", [])) or None
    allowed_dropout = set(filters.get("dropout", [])) or None
    allowed_logits = set(filters.get("logits", [])) or None
    allowed_qscale = set(filters.get("qscale", [])) or None
    allowed_vlayout = set(filters.get("vlayout", [])) or None
    allowed_skip = set(filters.get("skip", [])) or None
    allowed_sink = set(filters.get("sink", [])) or None
    allowed_trload = set(filters.get("trload", [])) or None
    allowed_spad = set(filters.get("spad", [])) or None
    allowed_skpad = set(filters.get("skpad", [])) or None
    allowed_dpad = set(filters.get("dpad", [])) or None
    allowed_dvpad = set(filters.get("dvpad", [])) or None

    def tune_filter(problem_ctx: "ProblemContext", kernel_ctx: "KernelContext") -> bool:
        p = kernel_ctx.pipeline
        if allowed_mode is not None and problem_ctx.mode not in allowed_mode:
            return False
        if allowed_mask is not None and p.F_mask not in allowed_mask:
            return False
        if allowed_bias is not None and p.F_bias not in allowed_bias:
            return False
        if allowed_lse is not None and p.F_lse not in allowed_lse:
            return False
        if allowed_dropout is not None and p.F_dropout not in allowed_dropout:
            return False
        if allowed_logits is not None and p.F_logits not in allowed_logits:
            return False
        if allowed_qscale is not None and p.F_qscale not in allowed_qscale:
            return False
        if allowed_vlayout is not None and p.F_vlayout not in allowed_vlayout:
            return False
        if (
            allowed_skip is not None
            and not (normalize_batch_skip and problem_ctx.mode == "batch")
            and p.F_skip not in allowed_skip
        ):
            return False
        if allowed_sink is not None and p.F_sink not in allowed_sink:
            return False
        if allowed_trload is not None and p.F_trload not in allowed_trload:
            return False
        if allowed_spad is not None and p.F_spad not in allowed_spad:
            return False
        if allowed_skpad is not None and p.F_skpad not in allowed_skpad:
            return False
        if allowed_dpad is not None and p.F_dpad not in allowed_dpad:
            return False
        if allowed_dvpad is not None and p.F_dvpad not in allowed_dvpad:
            return False
        return True

    return tune_filter


def _build_custom_tune_factory(cfg: dict):
    target = cfg.get("target", "")
    if not target:
        raise ValueError("[CustomTuneFactory] JSON 'target' field is required")
    base = _tune_config_pick_base(target)

    tiles_by_dtype = _parse_tune_config_tiles(cfg.get("tiles", {}))
    dtypes_whitelist = tuple(cfg.get("dtypes", ()))
    extra_rule = _make_tune_filter_rule(
        cfg.get("filters", {}), normalize_batch_skip=base.arch.name == "gfx125"
    )
    disable_hdim_rule = bool(
        cfg.get("relax_rules", {}).get("disable_check_hdim_tile", False)
    )

    class CustomTuneFactory(base):
        # arch inherited from base

        @classmethod
        def supported_dtypes(cls) -> Tuple[str]:
            base_dt = base.supported_dtypes()
            if dtypes_whitelist:
                return tuple(d for d in base_dt if d in dtypes_whitelist)
            # If not explicitly listed, restrict to dtypes appearing in tiles.
            return tuple(d for d in base_dt if d in tiles_by_dtype)

        @classmethod
        def get_hdim_tile_size_dict(cls, dtype: str) -> Optional[dict]:
            return tiles_by_dtype.get(dtype, None)

        @classmethod
        def get_rules(cls) -> List[CompatibilityRule]:
            rules = list(base.get_rules())
            if disable_hdim_rule:
                rules = [
                    r for r in rules if getattr(r, "__name__", "") != "check_hdim_tile"
                ]
            if extra_rule is not None:
                rules.append(extra_rule)
            return rules

    CustomTuneFactory.__name__ = f"CustomTuneFactory_{base.__name__}"
    return CustomTuneFactory


def get_factory(target: str):
    # Highest priority: JSON-driven tune-config factory.
    tune_cfg = _load_custom_tune_config()
    if tune_cfg is not None:
        return _build_custom_tune_factory(tune_cfg)

    if os.environ.get("CK_TILE_FMHA_FWD_CUSTOM_FACTORY", "0") == "1":
        return CustomFactory

    # Place more specific architectures first

    if target.startswith("gfx950"):
        return KernelComponentFactoryGfx950
    if target.startswith("gfx9"):
        return KernelComponentFactoryGfx9
    if target.startswith("gfx115"):
        return KernelComponentFactoryGfx115
    if target.startswith("gfx11"):
        return KernelComponentFactoryGfx11
    if target.startswith("gfx125"):
        return KernelComponentFactoryGfx125
    if target.startswith("gfx12"):
        return KernelComponentFactoryGfx12

    raise Exception(f"Unsupported device target {target}")


@dataclass(frozen=True)
class Product:
    name: str
    rule: CompatibilityRule

    def __call__(self, problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
        return self.rule(problem_ctx, kernel_ctx)


# Integrations must compile qr_tdm*_sched files with fmha_fwd_source_flags.cmake's per-file flags.
def get_product(receipt: int) -> Product:
    # Flash attention integration
    if receipt == 2:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            cond = problem_ctx.dtype in ["fp16", "bf16"]
            cond &= kernel_ctx.pipeline.F_vlayout == "row"
            cond &= kernel_ctx.pipeline.F_bias in ["no", "alibi"]
            cond &= kernel_ctx.pipeline.F_qscale == "no"
            cond &= kernel_ctx.pipeline.F_skip == "f"
            cond &= kernel_ctx.pipeline.F_sink == "f"
            # FlashAttention direct fwd wrappers always use softcap disabled and LSE enabled.
            cond &= kernel_ctx.pipeline.F_logits == "f"
            cond &= kernel_ctx.pipeline.F_lse == "t"
            return cond

        return Product(name="Flash attention integration", rule=fit)
    # Receipt 3 forward coverage used by CK library / smoke tests
    elif receipt == 3:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            cond = problem_ctx.dtype in ["fp16", "bf16"]
            cond &= kernel_ctx.pipeline.F_vlayout == "row"
            cond &= kernel_ctx.pipeline.F_bias in ["no", "alibi", "bias"]
            cond &= kernel_ctx.pipeline.F_qscale == "no"
            cond &= kernel_ctx.pipeline.F_skip == "f"
            return cond

        return Product(name="Flash attention integration", rule=fit)
    # PyTorch integration
    elif receipt == 4:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            cond = problem_ctx.dtype in ["fp16", "bf16"]
            cond &= kernel_ctx.pipeline.F_vlayout == "row"
            cond &= kernel_ctx.pipeline.F_bias in ["no", "bias"]
            cond &= kernel_ctx.pipeline.F_qscale == "no"
            cond &= kernel_ctx.pipeline.F_skip == "f"
            cond &= kernel_ctx.pipeline.F_logits == "f"
            return cond

        return Product(name="PyTorch integration", rule=fit)
    # CK Tile Python API
    elif receipt == 5:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            pipeline = kernel_ctx.pipeline
            if problem_ctx.dtype == "fp8bf16":
                return (
                    problem_ctx.hdim == problem_ctx.hdim_v <= 256
                    and pipeline.F_vlayout == "row"
                    and (
                        pipeline.F_qscale in ["no", "pertensor", "perhead"]
                        or (
                            problem_ctx.mode == "batch"
                            and pipeline.F_qscale == "blockscale"
                        )
                    )
                    and pipeline.F_bias == "no"
                    and pipeline.F_dropout == "f"
                    and pipeline.F_logits == "f"
                    and pipeline.F_skip == "f"
                    and pipeline.F_sink == "f"
                )
            cond = problem_ctx.dtype in ["fp16", "bf16"]
            cond &= problem_ctx.hdim == problem_ctx.hdim_v <= 256
            cond &= pipeline.F_vlayout == "row"
            cond &= pipeline.F_bias in ["no", "alibi"] or (
                problem_ctx.mode == "batch" and pipeline.F_bias == "bias"
            )
            cond &= pipeline.F_lse == "t"
            cond &= pipeline.F_logits == "f"
            cond &= pipeline.F_qscale == "no"
            cond &= pipeline.F_skip == "f"
            cond &= pipeline.F_sink == "f"
            return cond

        return Product(name="CK Tile Python API", rule=fit)
    # Aiter(mha_fwd) integration
    elif receipt == 100:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            cond = problem_ctx.dtype in ["fp16", "bf16", "fp8bf16"]
            cond &= problem_ctx.mode == "batch"
            cond &= kernel_ctx.pipeline.F_vlayout == "row"
            if problem_ctx.dtype == "fp8bf16":
                cond &= problem_ctx.hdim == 128 or problem_ctx.hdim == 192
            return cond

        return Product(name="Aiter(mha_fwd) integration", rule=fit)
    # Aiter(mha_varlen_fwd) integration
    elif receipt == 200:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            cond = problem_ctx.dtype in ["fp16", "bf16", "fp8bf16"]
            cond &= problem_ctx.mode == "group"
            cond &= kernel_ctx.pipeline.F_vlayout == "row"
            if problem_ctx.dtype == "fp8bf16":
                cond &= problem_ctx.hdim == 128 or problem_ctx.hdim == 192
            return cond

        return Product(name="Aiter(mha_varlen_fwd) integration", rule=fit)
    # aiter::mha_fwd C++ api integration
    elif receipt == 600:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            cond = problem_ctx.dtype in ["fp16", "bf16", "fp8bf16"]
            cond &= kernel_ctx.pipeline.F_vlayout == "row"
            if problem_ctx.dtype == "fp8bf16":
                cond &= problem_ctx.hdim == 128 or problem_ctx.hdim == 192
            return cond

        return Product(name="aiter::mha_fwd C++ api integration", rule=fit)
    # TransformerEngine integration
    elif receipt == 700:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            cond = problem_ctx.dtype in ["fp16", "bf16"]
            cond &= kernel_ctx.pipeline.F_vlayout == "row"
            cond &= kernel_ctx.pipeline.F_qscale == "no"
            cond &= kernel_ctx.pipeline.F_lse == "t"
            cond &= kernel_ctx.pipeline.F_skip == "f"
            cond &= kernel_ctx.pipeline.F_sink == "f"
            cond &= kernel_ctx.pipeline.F_logits == "f"
            return cond

        return Product(name="TransformerEngine integration", rule=fit)
    elif receipt == 888:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            cond = problem_ctx.dtype in ["fp8bf16", "fp8"]
            cond &= kernel_ctx.pipeline.F_vlayout == "row"
            cond &= problem_ctx.hdim == 128 or problem_ctx.hdim == 192
            return cond

        return Product(name="receipt = 888", rule=fit)
    # fp32 only, all variations
    elif receipt == 800:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            cond = problem_ctx.dtype == "fp32"
            cond &= kernel_ctx.pipeline.F_skip == "f"
            cond &= kernel_ctx.pipeline.F_logits == "f"
            return cond

        return Product(name="fp32 only, all variations", rule=fit)
    # fp32 only, minimal set of parameters
    elif receipt == 801:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            cond = problem_ctx.dtype == "fp32"
            cond &= problem_ctx.hdim in [48, 128]
            cond &= problem_ctx.mode == "batch"
            cond &= kernel_ctx.pipeline.F_bias == "no"
            cond &= kernel_ctx.pipeline.F_lse == "f"
            cond &= kernel_ctx.pipeline.F_dropout == "f"
            cond &= kernel_ctx.pipeline.F_skip == "f"
            cond &= kernel_ctx.pipeline.F_logits == "f"
            cond &= kernel_ctx.pipeline.F_mask == "s_no"
            return cond

        return Product(name="fp32 only, minimal set of parameters", rule=fit)
    # Don't build fp32 by default
    else:

        def fit(problem_ctx: ProblemContext, kernel_ctx: KernelContext) -> bool:
            return problem_ctx.dtype != "fp32"

        return Product(name="Default", rule=fit)


def get_fwd_blobs(
    targets: List[str], kernel_filter: Optional[str], receipt, optdim_list, mask_impl
) -> Tuple[FmhaFwdApiPool, List[FmhaFwdKernel]]:
    gen = list()
    api_pool = FmhaFwdApiPool()

    factories = get_factories_for_targets(targets, get_factory)

    for factory, dtype in ((f, t) for f in factories for t in f.supported_dtypes()):
        d = factory.get_hdim_tile_size_dict(dtype)
        # CustomTuneFactory might return None
        if not d:
            continue
        # for hdim_str, mode, mask, bias, lse in itertools.product(d.keys(), MODE_MAP.keys(), MASK_MAP.keys(), ["t", "f"], ["t", "f"]):
        for ((hdim, hdim_v), tiles), mode in itertools.product(
            d.items(), MODE_MAP.keys()
        ):
            if optdim_list != [-1] and hdim not in optdim_list:
                continue
            for tile, next_tile in zip(tiles, tiles[1:]):
                assert next_tile.F_bm0 >= tile.F_bm0, (
                    "Tiles must be ordered by increasing bm0"
                )

            for tile, pipeline in itertools.product(
                tiles, factory.get_pipelines(dtype, hdim, hdim_v, receipt, mask_impl)
            ):
                problem_ctx = ProblemContext(
                    dtype=dtype, mode=mode, hdim=hdim, hdim_v=hdim_v
                )
                kernel_ctx = KernelContext(
                    tile=tile, pipeline=pipeline, mask_impl=mask_impl
                )
                rules = factory.get_rules()
                product = get_product(receipt)

                # Skip changes only group-mode execution. Reuse skip=f in batch
                # dispatch instead of compiling identical skip=t instances.
                if (
                    factory.arch.name == "gfx125"
                    and mode == "batch"
                    and pipeline.F_skip == "t"
                ):
                    continue

                if not is_compatible(problem_ctx, kernel_ctx, [*rules, product]):
                    continue

                kernel = create_kernel(factory.arch, problem_ctx, kernel_ctx)
                if kernel_filter and not fnmatch.fnmatch(kernel.name, kernel_filter):
                    continue
                api_pool.register_traits(kernel.api_trait())
                gen.append(kernel)

    return (api_pool, gen)


def write_single_fwd_kernel(kernel: FmhaFwdKernel, autogen_dir: Path) -> None:
    update_file(autogen_dir / kernel.filename, kernel.render())


def write_fwd_api(
    api_pool: FmhaFwdApiPool,
    autogen_dir: Path,
) -> None:
    def accept_only_v3(trait: FmhaFwdApiTrait) -> bool:
        return trait.pipeline_tag == "qr_async_trload_v3"

    def accept_only_v2(trait: FmhaFwdApiTrait) -> bool:
        return not accept_only_v3(trait)

    content = "".join(
        [
            FMHA_FWD_API_HEADER,
            api_pool.render("fmha_fwd_v2", filter_fn=accept_only_v2),
            api_pool.render("fmha_fwd_v3", filter_fn=accept_only_v3),
            FMHA_FWD_API_FOOTER,
            api_pool.render_block_scale_size_kv(),
        ]
    )
    update_file(autogen_dir / FMHA_FWD_API_FILENAME, content)


def write_blobs(
    targets: List[str],
    output_dir: Path,
    kernel_filter: str,
    receipt,
    optdim_list,
    mask_impl,
) -> None:
    api_pool, kernels = get_fwd_blobs(
        targets, kernel_filter, receipt, optdim_list, mask_impl
    )
    for kernel in kernels:
        write_single_fwd_kernel(kernel, output_dir)
    write_fwd_api(api_pool, output_dir)


def list_blobs(
    targets: List[str],
    file_path: Path,
    kernel_filter: str,
    receipt,
    optdim_list,
    mask_impl,
) -> None:
    with file_path.open("a") as f:
        _, kernels = get_fwd_blobs(
            targets, kernel_filter, receipt, optdim_list, mask_impl
        )
        for kernel in kernels:
            f.write((file_path.parent / GEN_DIR / kernel.filename).as_posix() + "\n")
        f.write((file_path.parent / GEN_DIR / FMHA_FWD_API_FILENAME).as_posix() + "\n")
