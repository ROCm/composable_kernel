# bf16 d128, 4096 queries per batch: pingpong is ahead up to 512 keys (1.13 vs 1.18 ms), sched
# from 1024 (0.91 vs 1.05 ms; 0.72 vs 1.00 ms at 8192). Softmax calls follow
