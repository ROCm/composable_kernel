@dataclass
class CppConstraint:
    bool_expr: str = None

    def __str__(self):
        if self.bool_expr is None:
            return "true"
        else:
            return f"{self.bool_expr}"

    def __and__(self, other):
        return CppConstraint(f"({str(self)}) && ({str(other)})")


@dataclass
class FmhaFwdApiTrait:
    arch: ArchTrait
    pipeline_tag: str
    # sync with fmha_fwd_traits<>, to generate fallback calls
    hdim: str
    dtype: str  # data type
    mode: str  # value from MODE_MAP
    bm0: int  # tile size along q seqlen (block size)
    bn0: int  # tile size along qk seqlen
    bk0: int  # tile size along qk gemm unroll
    bn1: int  # tile size along v head_dim
    bk1: int  # tile size along kv gemm unroll
    bk0max: int
    vlayout: str
    logits: str
    mask: str
    bias: str  #
    lse: str  #
    dropout: str
    qscale: str  #
    spad: str
    skpad: str
    dpad: str
    dvpad: str
    skip: str
    tr_load: str
    sink: str
    # Metadata-only hint mapped onto fmha_fwd_traits_::kOccupancy. Its sole
    # purpose here is to make otherwise-identical traits produce DISTINCT
    # template instantiations of `fmha_fwd_<traits, arch>`, so multiple
    # occupancy variants for the same tile can coexist in one shared object.
    occupancy: int = -1
    constraint: CppConstraint = field(default_factory=lambda: CppConstraint())
    packgqa: str = "f"

    @property
    def name(self) -> str:
        return (
            f"{self.hdim}-{self.dtype}-{self.mode}-{self.bm0}-{self.bn0}-{self.bk0}-{self.bn0}-{self.bk1}-{self.bk0max}-"
            + f"{self.vlayout}-{self.logits}-{self.mask}-{self.bias}-{self.lse}-{self.dropout}-{self.qscale}-{self.spad}-{self.skpad}-{self.dpad}-{self.dvpad}-{self.skip}-{self.sink}"
        )

    @property
    def scheck(self) -> str:
        if self.mode == "group":
            return "true/*group mode spad always true*/"  # group mode only generate spad/skpad == true
        if self.pipeline_tag in [
            "qr_async",
            "qr_async_trload",
            "qr_async_trload_v3",
            "qr_tdm",
            "qr_tdm_sched",
            "qr_tdm_fp8_sched",
            "qr_tdm_pingpong",
        ]:
            if self.spad == "t":
                return "true"  # always support
            else:
                return "true"
        elif self.pipeline_tag in ["qr", "qr_hpad", "qs"]:
            if self.spad == "t":
                return f"true /*a.seqlen_q % {self.bm0} != 0*/"  # TODO: order of get_pipelines() matters! (ugly)
            else:
                return f"a.seqlen_q % {self.bm0} == 0"
        else:
            assert False

    def seqtune(self, max_bm0: int) -> str:
        if self.bm0 == max_bm0 or self.bm0 == 64:
            return "true/*fall back to largest tile*/"
        else:
            if self.mode == "group":
                return f"a.max_seqlen_q <= {self.bm0}"
            return f"a.seqlen_q <= {self.bm0}"

    @property
    def skcheck(self) -> str:
        if self.mode == "group":
            return "true/*group mode skpad always true*/"  # group mode only generate spad/skpad == true
        if self.pipeline_tag == "qr_async":
            if self.skpad == "t":
                return f"(a.cu_seqlen_k_ptr != nullptr) || (a.seqlen_k == 0 || a.seqlen_k % {self.bn0} != 0)"
            else:
                return f"(a.cu_seqlen_k_ptr == nullptr) && (a.seqlen_k != 0 && a.seqlen_k % {self.bn0} == 0)"
        elif self.pipeline_tag in ["qr", "qr_hpad", "qs"]:
            if self.skpad == "t":
                return f"true /*a.seqlen_k % {self.bn0} != 0*/"  # TODO: order of get_pipelines() matters! (ugly)
            else:
                return f"(a.cu_seqlen_k_ptr == nullptr) && (a.seqlen_k != 0 && a.seqlen_k % {self.bn0} == 0)"
        elif self.pipeline_tag == "qr_tdm_pingpong":
            # It zero-fills the K/V rows past seqlen_k and masks the last S tile,
            # so the unpadded instance serves any seqlen_k; an elementwise bias
            # is vector-loaded and still needs whole tiles.
            if self.skpad == "t" or self.bias != "bias":
                return "true"
            else:
                return f"(a.cu_seqlen_k_ptr == nullptr) && (a.seqlen_k != 0 && a.seqlen_k % {self.bn0} == 0)"
        elif self.pipeline_tag == "qr_tdm" or (
            self.pipeline_tag == "qr_tdm_sched" and self.hdim == "64"
        ):
            if self.skpad == "t":
                return "true"
            else:
                return f"(a.cu_seqlen_k_ptr == nullptr) && (a.seqlen_k != 0 && a.seqlen_k % {self.bn0} == 0)"
        elif self.pipeline_tag in [
            "qr_async_trload",
            "qr_async_trload_v3",
            "qr_tdm_sched",
            "qr_tdm_fp8_sched",
        ]:
            if self.skpad == "t":
                return "true"
            else:
                return "true"
        else:
            assert False

    @property
    def dcheck(self) -> str:
        if self.pipeline_tag == "qr_hpad":
            if self.dpad == "t":
                return "a.hdim_q % 8 == 0"
            else:
                assert False
        elif self.pipeline_tag in ["qr_tdm", "qr_tdm_pingpong"]:
            if self.dpad == "t":
                return (
                    "true"
                    if self.pipeline_tag == "qr_tdm" and self.dtype in ("fp16", "bf16")
                    else "a.hdim_q % 8 == 0"
                )
            return f"a.hdim_q % {TDM_K0_MAX_SUBMAX_MAP[self.bk0max]} == 0"
        elif self.pipeline_tag in [
            "qr",
            "qs",
            "qr_async",
            "qr_async_trload",
            "qr_async_trload_v3",
            "qr_tdm_sched",
            "qr_tdm_fp8_sched",
        ]:
            bk0submax = K0_MAX_SUBMAX_MAP[self.bk0max]
            if self.dpad == "t":
                return f"true /*a.hdim_q % {bk0submax} != 0*/"  # TODO: order of get_pipelines() matters! (ugly)
            else:
                return f"a.hdim_q % {bk0submax} == 0"
        else:
            assert False

    @property
    def dvcheck(self) -> str:
        if self.pipeline_tag == "qr_hpad":
            if self.dvpad == "t":
                return "a.hdim_v % 8 == 0"
            else:
                assert False
        elif self.pipeline_tag in ["qr_tdm", "qr_tdm_pingpong"]:
            if self.dvpad == "t":
                return (
                    "true"
                    if self.pipeline_tag == "qr_tdm" and self.dtype in ("fp16", "bf16")
                    else "a.hdim_v % 8 == 0"
                )
            return f"a.hdim_v % {TDM_K0_MAX_SUBMAX_MAP[self.bk0max]} == 0"
        elif self.pipeline_tag in [
            "qr",
            "qs",
            "qr_async",
            "qr_async_trload",
            "qr_async_trload_v3",
            "qr_tdm_sched",
            "qr_tdm_fp8_sched",
        ]:
            # FP8 sched tiles may have hdim_v below hdim_q (D192/V128), so check V's own width.
            v_width = (
                self.bn1 if self.pipeline_tag == "qr_tdm_fp8_sched" else self.bk0max
            )
            bk0submax = K0_MAX_SUBMAX_MAP[v_width]
            if self.dvpad == "t":
                return f"true /*a.hdim_v % {bk0submax} != 0*/"  # TODO: order of get_pipelines() matters! (ugly)
            else:
                return f"a.hdim_v % {bk0submax} == 0"
        else:
            assert False


@dataclass
class FmhaFwdPipeline:
    tag: str

    F_vlayout: str  # row/col
    F_spad: str  # true/false
    F_skpad: str  #
    F_dpad: str  #
    F_dvpad: str  #
    F_logits: str  # t/f
    F_bias: str  # true/false
    F_lse: str  #
    F_dropout: str  #
    F_qscale: str  # no/pertensor
    F_mask: str  # value from MASK_MAP
    F_skip: str  # true/false
    F_trload: str  # true/false
    F_sink: str  # true/false
    F_constraint: CppConstraint = field(default_factory=lambda: CppConstraint())
    F_use_double_kv_lds_buffer: str = "f"  # true/false
    F_progressive_ds_load_k: str = "f"  # true/false
    F_packgqa: str = "f"  # true/false

    @property
    def name(self) -> str:
        def pad_name() -> str:
            n = ""
            if self.F_spad == "t":
                n += "s"
            if self.F_skpad == "t":
                n += "sk"
            if self.F_dpad == "t":
                n += "d"
            if self.F_dvpad == "t":
                n += "dv"
            if n != "":
                n = "p" + n
            return n

        pn = pad_name()
        n = f"{self.tag}_v{self.F_vlayout[0]}"
        if pn != "":
            n += f"_{pn}"
        else:
            n += "_npad"

        if self.F_logits == "t":
            n += "_logits"
        else:
            n += "_nlogits"

        if self.F_bias != "no":
            n += f"_{self.F_bias}"
        else:
            n += "_nbias"

        if self.F_mask[0:2] == "s_":
            if self.F_mask == "s_mask":
                n += "_mask"
            else:
                n += "_nmask"
        else:
            if self.F_mask != "no":
                n += f"_m{self.F_mask[0]}"
            else:
                n += "_nmask"

        if self.F_lse == "t":
            n += "_lse"
        else:
            n += "_nlse"

        if self.F_dropout == "t":
            n += "_dropout"
        else:
            n += "_ndropout"

        if self.F_skip == "t":
            n += "_skip"
        else:
            n += "_nskip"

        if self.F_qscale != "no":
            n += f"_{self.F_qscale}"
        else:
            n += "_nqscale"

        if self.F_trload == "t":
            n += "_trload"
        else:
            n += "_ntrload"
        if self.tag == "qr_tdm":
            if self.F_use_double_kv_lds_buffer == "t":
                n += "_kvlp"
            else:
                n += "_nkvlp"
            if self.F_progressive_ds_load_k == "t":
                n += "_plk"
            else:
                n += "_nplk"
        if self.tag == "qr_tdm_fp8_sched":
            if self.F_packgqa == "t":
                n += "_packgqa"
            else:
                n += "_npackgqa"
        if self.F_sink == "t":
            n += "_sink"
        else:
            n += "_nsink"

        return n


