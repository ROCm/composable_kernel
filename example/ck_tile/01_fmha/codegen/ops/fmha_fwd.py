    # 128-row tile as BlockFmhaPipelineQRKSVSTdmGdpaQLoop
    F_activation: str = "softmax"
    # qr_tdm_pingpong's LDS read schedule (QrTdmPingPongLdsReadSchedule); FmhaFwdKernel
    # keeps only what takes effect on its tile (see qr_tdm_pingpong_effective_schedule)
    F_pp_slice_prefetch: int = 0  # tiles of >= this many rows prefetch the next slice
    F_pp_v_before_softmax: int = 0  # tiles of >= this many rows read V early
    F_packgqa: str = "f"  # true/false

    @property
    def name(self) -> str:
        def pad_name() -> str:
            n = ""
            if self.F_spad == "t":
                n += "s"
            if self.F_skpad == "t":
                n += "sk"
            if self.F_dpad == "t":
                n += "d"
            if self.F_dvpad == "t":
                n += "dv"
            if n != "":
                n = "p" + n
            return n

        pn = pad_name()
        n = f"{self.tag}_v{self.F_vlayout[0]}"
        if pn != "":
            n += f"_{pn}"
        else:
            n += "_npad"

        if self.F_logits == "t":
            n += "_logits"
        else:
            n += "_nlogits"

        if self.F_bias != "no":
            n += f"_{self.F_bias}"
        else:
            n += "_nbias"

        if self.F_mask[0:2] == "s_":
            if self.F_mask == "s_mask":
                n += "_mask"
            else:
                n += "_nmask"
        else:
            if self.F_mask != "no":
                n += f"_m{self.F_mask[0]}"
            else:
                n += "_nmask"

        if self.F_lse == "t":
            n += "_lse"
        else:
            n += "_nlse"

        if self.F_dropout == "t":
            n += "_dropout"
        else:
            n += "_ndropout"

        if self.F_skip == "t":
            n += "_skip"
        else:
            n += "_nskip"

        if self.F_qscale != "no":
            n += f"_{self.F_qscale}"
        else:
            n += "_nqscale"

        if self.F_trload == "t":
            n += "_trload"
        else:
            n += "_ntrload"
        if self.tag == "qr_tdm":
            if self.F_use_double_kv_lds_buffer == "t":
                n += "_kvlp"
            else:
                n += "_nkvlp"
            if self.F_progressive_ds_load_k == "t":
                n += "_plk"
            else:
                n += "_nplk"
        if self.tag == "qr_tdm_pingpong":
            # only a schedule that takes effect is named; the default one adds nothing
            if self.F_pp_slice_prefetch > 0:
                n += f"_sp{self.F_pp_slice_prefetch}"
            if self.F_pp_v_before_softmax > 0:
                n += f"_vbs{self.F_pp_v_before_softmax}"
            if self.F_packgqa == "t":
                n += "_packgqa"
        if self.tag == "qr_tdm_fp8_sched":
            if self.F_packgqa == "t":
                n += "_packgqa"
            else:
                n += "_npackgqa"
        if self.F_sink == "t":
            n += "_sink"
        else:
            n += "_nsink"
        if self.F_activation != "softmax":
            n += f"_{self.F_activation}"

        return n


