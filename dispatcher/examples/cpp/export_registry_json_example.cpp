/**
 * Example: Export Dispatcher Registry to JSON
 * 
 * Demonstrates how to export all registered kernels to JSON format,
 * similar to the tile engine benchmarking JSON export.
 * 
 * Usage:
 *   ./export_registry_json_example [output.json]
 * 
 * Output:
 *   - Prints registry summary to console
 *   - Optionally exports full JSON to file
 */

#include "ck_tile/dispatcher/registry.hpp"
#include "ck_tile/dispatcher/dispatcher.hpp"
#include "ck_tile/dispatcher/json_export.hpp"

// Include generated kernel registration
// (These would be auto-generated by unified_gemm_codegen.py)
#ifdef HAVE_GENERATED_KERNELS
#include "generated_kernels/register_all_kernels.hpp"
#endif

#include <iostream>
#include <string>

using namespace ck_tile::dispatcher;

void print_json_preview(const std::string& json, size_t max_lines = 20) {
    std::istringstream stream(json);
    std::string line;
    size_t count = 0;
    
    std::cout << "\n=== JSON Preview (first " << max_lines << " lines) ===\n";
    while (std::getline(stream, line) && count < max_lines) {
        std::cout << line << "\n";
        count++;
    }
    std::cout << "... (use --full to see complete JSON)\n";
}

int main(int argc, char* argv[]) {
    std::cout << "=== Dispatcher Registry JSON Export Example ===\n\n";
    
    // Get registry instance
    auto& registry = Registry::instance();
    
    std::cout << "Total registered kernels: " << registry.size() << "\n";
    
    if (registry.size() == 0) {
        std::cout << "\n[INFO] No kernels registered yet.\n";
        std::cout << "This example works best after kernels are registered.\n";
        std::cout << "\nTo register kernels:\n";
        std::cout << "  1. Generate kernels: cd codegen && python3 unified_gemm_codegen.py\n";
        std::cout << "  2. Build with kernels: cmake -DBUILD_DISPATCHER_EXAMPLES=ON\n";
        std::cout << "  3. Run this example again\n\n";
        
        // Show example with empty registry
        std::cout << "Example JSON output with empty registry:\n";
        std::string json = registry.export_json();
        std::cout << json << "\n";
        return 0;
    }
    
    // Export to JSON string
    std::cout << "\n--- Method 1: Export to JSON string ---\n";
    std::string json_with_stats = registry.export_json(true);
    std::cout << "JSON size: " << json_with_stats.size() << " bytes\n";
    print_json_preview(json_with_stats, 30);
    
    // Export without statistics (smaller output)
    std::cout << "\n--- Method 2: Export without statistics ---\n";
    std::string json_no_stats = registry.export_json(false);
    std::cout << "JSON size: " << json_no_stats.size() << " bytes\n";
    std::cout << "(Reduced by " << (json_with_stats.size() - json_no_stats.size()) << " bytes)\n";
    
    // Export to file if filename provided
    if (argc > 1) {
        std::string output_file = argv[1];
        std::cout << "\n--- Method 3: Export to file ---\n";
        std::cout << "Writing to: " << output_file << "\n";
        
        bool success = registry.export_json_to_file(output_file, true);
        if (success) {
            std::cout << "✓ Successfully exported to " << output_file << "\n";
            std::cout << "\nYou can now inspect the file:\n";
            std::cout << "  cat " << output_file << " | python3 -m json.tool\n";
            std::cout << "  or\n";
            std::cout << "  python3 -c \"import json; data=json.load(open('" << output_file 
                      << "')); print(data['metadata'])\"\n";
        } else {
            std::cerr << "✗ Failed to export to " << output_file << "\n";
            return 1;
        }
    } else {
        std::cout << "\n[TIP] Provide filename as argument to save JSON to file:\n";
        std::cout << "  " << argv[0] << " kernels.json\n";
    }
    
    // Print some useful information from the registry
    std::cout << "\n=== Kernel Summary ===\n";
    auto all_kernels = registry.get_all();
    
    if (!all_kernels.empty()) {
        std::cout << "\nFirst 5 kernels:\n";
        for (size_t i = 0; i < std::min(size_t(5), all_kernels.size()); ++i) {
            const auto& kernel = all_kernels[i];
            const auto& key = kernel->get_key();
            
            std::cout << "\n" << (i+1) << ". " << kernel->get_name() << "\n";
            std::cout << "   Identifier: " << key.encode_identifier() << "\n";
            std::cout << "   Tile Shape: " << key.algorithm.tile_shape.m << "x" 
                      << key.algorithm.tile_shape.n << "x" 
                      << key.algorithm.tile_shape.k << "\n";
            std::cout << "   Pipeline: " << pipeline_to_string(key.algorithm.pipeline) << "\n";
            std::cout << "   Scheduler: " << scheduler_to_string(key.algorithm.scheduler) << "\n";
            std::cout << "   Persistent: " << (key.algorithm.persistent ? "yes" : "no") << "\n";
            std::cout << "   GFX Arch: " << key.gfx_arch << "\n";
        }
        
        if (all_kernels.size() > 5) {
            std::cout << "\n... and " << (all_kernels.size() - 5) << " more kernels\n";
            std::cout << "(see JSON export for complete list)\n";
        }
    }
    
    std::cout << "\n=== Complete ===\n";
    return 0;
}

